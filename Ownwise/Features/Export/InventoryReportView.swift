import SwiftUI

/// The summary page of the inventory report (E4): what is owned, and what it cost — the list an
/// insurer asks for. Rendered to PDF by `ExportService`.
///
/// Every total is per currency (E10). A list that adds different currencies together is worse than no
/// list at all, because the wrong number looks exactly as authoritative as the right one.
struct InventoryReportView: View {
    let summary: InventorySummary.Summary
    let service: ExportService

    var body: some View {
        VStack(alignment: .leading, spacing: 20) {
            VStack(alignment: .leading, spacing: 4) {
                Text("Inventory").font(.caption.weight(.semibold)).foregroundStyle(.secondary)
                Text("My things").font(.largeTitle.bold())
                Text(subtitle).font(.title3).foregroundStyle(.secondary)
            }

            if summary.totalsByCurrency.isEmpty {
                Text("No prices recorded yet. Adding what you paid makes this report usable as an insurance list.")
                    .font(.body)
            } else {
                VStack(alignment: .leading, spacing: 6) {
                    Text("Recorded value").font(.headline)
                    Grid(alignment: .leading, horizontalSpacing: 16, verticalSpacing: 6) {
                        ForEach(InventorySummary.sortedCurrencies(summary.totalsByCurrency), id: \.self) { code in
                            GridRow {
                                Text(code).foregroundStyle(.secondary)
                                Text(Money.formatted(summary.totalsByCurrency[code] ?? 0, currencyCode: code)).bold()
                            }
                        }
                    }
                    Text("What you paid when you bought each thing, not what it would sell for now.")
                        .font(.footnote).foregroundStyle(.secondary)
                }
            }

            if !summary.totalsByCategory.isEmpty {
                VStack(alignment: .leading, spacing: 6) {
                    Text("By category").font(.headline)
                    Grid(alignment: .leading, horizontalSpacing: 16, verticalSpacing: 6) {
                        ForEach(ItemCategory.allCases, id: \.self) { category in
                            let totals = summary.totalsByCategory[category] ?? [:]
                            if !totals.isEmpty {
                                GridRow {
                                    Text(category.label)
                                    Text(InventorySummary.sortedCurrencies(totals)
                                        .map { Money.formatted(totals[$0] ?? 0, currencyCode: $0) }
                                        .joined(separator: " · "))
                                        .bold()
                                }
                            }
                        }
                    }
                }
            }

            Spacer()
            Text("Generated by Ownwise on \(service.now.formatted(date: .long, time: .omitted))")
                .font(.caption).foregroundStyle(.secondary)
        }
        .padding(40)
    }

    private var subtitle: String {
        let count = InventorySummary.itemsPhrase(summary.itemCount)
        if summary.pricedItemCount == 0 {
            return String(localized: "\(count) · no prices recorded", comment: "Inventory report subtitle")
        }
        if summary.pricedItemCount < summary.itemCount {
            return String(localized: "\(count) · \(summary.pricedItemCount) with a price",
                          comment: "Inventory report subtitle")
        }
        return count
    }
}

/// The pages that list the items themselves, one chunk per page: a long library must not be silently
/// clipped to a single page.
struct InventoryItemsPageView: View {
    let lines: [InventorySummary.Line]
    let page: Int
    let of: Int

    var body: some View {
        VStack(alignment: .leading, spacing: 16) {
            if of > 1 {
                Text("Items \(page) of \(of)").font(.headline)
            } else {
                Text("Items").font(.headline)
            }

            Grid(alignment: .leading, horizontalSpacing: 16, verticalSpacing: 8) {
                GridRow {
                    Text("Item").bold()
                    Text("Bought").bold()
                    Text("Price").bold()
                }
                ForEach(lines, id: \.id) { line in
                    GridRow {
                        VStack(alignment: .leading, spacing: 2) {
                            Text(line.name)
                            Text(line.category.label).font(.caption).foregroundStyle(.secondary)
                        }
                        Text(line.purchaseDate.formatted(date: .abbreviated, time: .omitted))
                        Text(Money.formatted(line.priceMinor, currencyCode: line.currencyCode))
                    }
                }
            }

            Spacer()
        }
        .padding(40)
    }
}
